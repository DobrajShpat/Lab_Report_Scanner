class LoincCatalog:
    def __init__(self, catalog_path: Path) -> None:
        self._payload = orjson.loads(catalog_path.read_bytes())
        self.tests = self._merge_tests(self._payload["tests"], ADDITIONAL_TESTS)

    def items(self) -> list[dict[str, Any]]:
        return list(self.tests)

    @staticmethod
    def _merge_tests(primary: list[dict[str, Any]], additional: list[dict[str, Any]]) -> list[dict[str, Any]]:
        merged: dict[tuple[str, str], dict[str, Any]] = {}
        for item in primary + additional:
            key = (item["canonical_name"], item["loinc_code"])
            if key in merged:
                existing_aliases = set(merged[key].get("aliases", []))
                existing_aliases.update(item.get("aliases", []))
                merged[key]["aliases"] = sorted(existing_aliases)
                merged[key].update({k: v for k, v in item.items() if k != "aliases"})
                continue
            merged[key] = dict(item)
        return list(merged.values())
